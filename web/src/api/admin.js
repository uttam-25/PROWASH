import api from './axios'
export const adminAPI = {
  getDashboard: () => api.get('/admin/dashboard'),
  getReports: () => api.get('/admin/reports'),
  getBookings: (params = {}) => api.get('/admin/bookings', { params }),
  getBooking: (id) => api.get(`/admin/bookings/${id}`),
  updateBookingStatus: (id, status, note = '') => api.patch(`/admin/bookings/${id}/status`, { status, note }),
  getServices: (params = {}) => api.get('/services', { params: { ...params, includeInactive: true } }),
  createService: (data) => api.post('/admin/services', data),
  updateService: (id, data) => api.patch(`/admin/services/${id}`, data),
  deleteService: (id) => api.delete(`/admin/services/${id}`),
  getCustomers: (params = {}) => api.get('/admin/customers', { params }),
  getCustomer: (id) => api.get(`/admin/customers/${id}`),
  getVehicles: (params = {}) => api.get('/admin/vehicles', { params }),
  getPayments: (params = {}) => api.get('/admin/payments', { params }),
  collectCOD: (id) => api.patch(`/admin/payments/${id}/collect`),
  getSchedule: () => api.get('/admin/schedule'),
  updateSchedule: (data) => api.put('/admin/schedule', data),
  addBlockedPeriod: (data) => api.post('/admin/schedule/block', data),
  removeBlockedPeriod: (id) => api.delete(`/admin/schedule/block/${id}`),
  addHoliday: (data) => api.post('/admin/schedule/holiday', data),
  removeHoliday: (id) => api.delete(`/admin/schedule/holiday/${id}`),
  getPartners: (params = {}) => api.get('/admin/partners', { params }),
  getPartner: (id) => api.get(`/admin/partners/${id}`),
  verifyPartner: (id) => api.patch(`/admin/partners/${id}/verify`),
  deactivatePartner: (id) => api.patch(`/admin/partners/${id}/deactivate`),
}
